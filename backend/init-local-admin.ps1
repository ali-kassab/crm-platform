# Creates LOCAL-DEVELOPMENT platform-admin credentials in the repo-root .env (once).
#
# - Appends PLATFORM_ADMIN_EMAIL and a strong random PLATFORM_ADMIN_PASSWORD (24 characters) to ..\.env.
# - Refuses if either variable is already present: existing credentials are never overwritten.
# - Refuses unless DB_URL in .env points at a local database (localhost / 127.0.0.1): never use this
#   for staging or production; set explicit, private credentials there instead.
# - Never prints the password. Read it from .env yourself.
#
# The account itself is created by the backend at its next start (PlatformAdminBootstrap), once,
# and only if no platform admin exists yet. Restarts never reset it.
# Usage (from backend/):  .\init-local-admin.ps1
$ErrorActionPreference = 'Stop'
$envFile = Join-Path $PSScriptRoot '..\.env'
if (-not (Test-Path $envFile)) { throw "Missing $envFile - copy .env.example to .env first." }
$lines = Get-Content $envFile
if ($lines | Where-Object { $_ -match '^\s*PLATFORM_ADMIN_(EMAIL|PASSWORD)\s*=' }) {
    Write-Host 'PLATFORM_ADMIN_EMAIL / PLATFORM_ADMIN_PASSWORD already exist in .env - nothing changed.'
    exit 0
}
$dbUrl = ($lines | Where-Object { $_ -match '^\s*DB_URL\s*=' } | Select-Object -First 1) -replace '^\s*DB_URL\s*=\s*', ''
if ($dbUrl -notmatch '^jdbc:postgresql://(localhost|127\.0\.0\.1)(:\d+)?/') {
    throw 'DB_URL in .env is not a local database; refusing to generate admin credentials for it.'
}

$rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
function Get-RandomIndex([int]$max) {
    $bytes = New-Object byte[] 4
    do { $rng.GetBytes($bytes); $n = [BitConverter]::ToUInt32($bytes, 0) } while ($n -ge [uint32]::MaxValue - ([uint32]::MaxValue % $max))
    return [int]($n % $max)
}
$lower = 'abcdefghijkmnopqrstuvwxyz'; $upper = 'ABCDEFGHJKLMNPQRSTUVWXYZ'; $digits = '23456789'; $symbols = '-_.+~'
$all = $lower + $upper + $digits + $symbols
# one of each class, then 20 more, then shuffle (Fisher-Yates)
$chars = @($lower[(Get-RandomIndex $lower.Length)], $upper[(Get-RandomIndex $upper.Length)],
    $digits[(Get-RandomIndex $digits.Length)], $symbols[(Get-RandomIndex $symbols.Length)])
for ($i = 0; $i -lt 20; $i++) { $chars += $all[(Get-RandomIndex $all.Length)] }
for ($i = $chars.Count - 1; $i -gt 0; $i--) { $j = Get-RandomIndex ($i + 1); $t = $chars[$i]; $chars[$i] = $chars[$j]; $chars[$j] = $t }
$password = -join $chars
$suffix = -join (1..6 | ForEach-Object { '0123456789abcdef'[(Get-RandomIndex 16)] })
$email = "platform-admin-$suffix@crm-platform.test"

$block = @('', '# Local development platform admin (generated by backend/init-local-admin.ps1).',
    '# Used once by the backend at startup to create the first platform admin; never commit this file.',
    "PLATFORM_ADMIN_EMAIL=$email", "PLATFORM_ADMIN_PASSWORD=$password")
[System.IO.File]::AppendAllText((Resolve-Path $envFile), ($block -join "`n") + "`n", (New-Object System.Text.UTF8Encoding $false))
Write-Host "Added PLATFORM_ADMIN_EMAIL=$email and a 24-character PLATFORM_ADMIN_PASSWORD to .env (password not shown)."
Write-Host 'Restart the backend once; look for "Platform admin account created from the environment".'
